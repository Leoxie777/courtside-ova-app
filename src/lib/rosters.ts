/** Maps CSV team ids (T001) to app team ids (t1). Returns null when no app team matches. */
export function toAppTeamId(sourceId: string): string | null {
  const m = /^T0*(\d+)$/i.exec(sourceId.trim());
  if (!m) return null;
  const id = `t${m[1]}`;
  return teams.some((t) => t.id === id) ? id : null;
}

